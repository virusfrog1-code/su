const dictionary: Record<Locale, LocaleDictionary> = { en, zh, ko, ja };

type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);
const localeToHtmlLang: Record<Locale, string> = {
  en: "en",
  zh: "zh-CN",
  ko: "ko",
  ja: "ja"
};

function isLocale(value: string | null): value is Locale {
  return value === "en" || value === "zh" || value === "ko" || value === "ja";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    if (typeof window === "undefined") return "en";
    const saved = window.localStorage.getItem("summon-locale");
    return isLocale(saved) ? saved : "en";
  });

  const value = useMemo<I18nContextValue>(() => {
    const setLocale = (nextLocale: Locale) => {
      setLocaleState(nextLocale);
      window.localStorage.setItem("summon-locale", nextLocale);
      document.documentElement.lang = localeToHtmlLang[nextLocale];
    };

    return {
      locale,
      setLocale,
      t: (key, vars) => withVars(dictionary[locale][key] || dictionary.en[key], vars)
    };
  }, [locale]);

  useEffect(() => {
    document.documentElement.lang = localeToHtmlLang[locale];
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}
